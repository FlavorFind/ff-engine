def main():
    # 1. Add new ingredients
    ing_path = os.path.join(BASE, "data/seeds/ingredients.csv")
    with open(ing_path) as f:
        existing_slugs = {row["slug"] for row in csv.DictReader(f)}

    new_ings = [row for row in NEW_INGREDIENTS if row[0] not in existing_slugs]
    if new_ings:
        with open(ing_path, "a", newline="") as f:
            writer = csv.writer(f)
            for row in new_ings:
                writer.writerow(row)
        print(
            f"Added {len(new_ings)} new ingredients (total now {len(existing_slugs) + len(new_ings)})"
        )
    else:
        print("No new ingredients to add")

    # 2. Add new dishes
    dish_path = os.path.join(BASE, "data/seeds/dishes.csv")
    with open(dish_path) as f:
        existing_dish_slugs = {row["slug"] for row in csv.DictReader(f)}

    new_dishes = [row for row in NEW_DISHES if row[0] not in existing_dish_slugs]
    if new_dishes:
        with open(dish_path, "a", newline="") as f:
            writer = csv.writer(f)
            for row in new_dishes:
                writer.writerow(row)
        print(
            f"Added {len(new_dishes)} new dishes (total now {len(existing_dish_slugs) + len(new_dishes)})"
        )
    else:
        print("No new dishes to add")

    # 3. Add dish ingredient links
    link_path = os.path.join(BASE, "data/seeds/dish_ingredients.csv")
    with open(link_path) as f:
        existing_links = set()
        for row in csv.DictReader(f):
            existing_links.add((row["dish_slug"], row["ingredient_slug"], row["position"]))

    new_links = []
    for dish_slug, links in DISH_LINKS.items():
        for i, (ing_slug, role, qty) in enumerate(links, 1):
            key = (dish_slug, ing_slug, str(i))
            if key not in existing_links:
                new_links.append((dish_slug, ing_slug, role, qty, "", i))

    if new_links:
        with open(link_path, "a", newline="") as f:
            writer = csv.writer(f)
            for row in new_links:
                writer.writerow(row)
        print(f"Added {len(new_links)} new dish-ingredient links")
    else:
        print("No new dish-ingredient links to add")

    # 4. Extend golden set
    golden_path = os.path.join(BASE, "data/golden/golden_set_v0.json")
    with open(golden_path) as f:
        golden = json.load(f)

    existing_case_ids = {c["id"] for c in golden["cases"]}
    new_cases = [c for c in NEW_GOLDEN_CASES if c["id"] not in existing_case_ids]

    if new_cases:
        golden["cases"].extend(new_cases)
        with open(golden_path, "w") as f:
            json.dump(golden, f, indent=2)
        print(f"Added {len(new_cases)} new golden set cases (total now {len(golden['cases'])})")
    else:
        print("No new golden set cases to add")

    # Summary
    print("\n=== E44 Data Expansion Summary ===")
    with open(ing_path) as f:
        total_ings = sum(1 for _ in csv.DictReader(f))
    with open(dish_path) as f:
        total_dishes = sum(1 for _ in csv.DictReader(f))
    with open(golden_path) as f:
        total_cases = len(json.load(f)["cases"])
    print(f"Ingredients: {total_ings}")
    print(f"Dishes: {total_dishes}")
    print(f"Golden set cases: {total_cases}")


if __name__ == "__main__":
    main()
